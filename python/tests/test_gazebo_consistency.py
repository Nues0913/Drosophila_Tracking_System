"""#88 2D/Gazebo input consistency comparison (gazebo_consistency_compare.py)."""

import importlib.util
import json
from pathlib import Path

import numpy as np
import pytest
from flytrack_core.sensing.olfaction import odor_sensor_positions
from flytrack_core.world import make_plume
from flytrack_sim.env import FlyTrackEnv

ROOT = Path(__file__).resolve().parents[2]


def compare_module():
    spec = importlib.util.spec_from_file_location(
        "gazebo_consistency_compare_test",
        ROOT / "scripts/diagnostics/gazebo_consistency_compare.py",
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def synthetic_export(module, env, vision_transform=lambda v: v):
    """A Gazebo-like export whose inputs are generated by the 2D world itself."""
    parameters = {
        "episode_start_s": 0.5,
        "arena_size_m": 10.0,
        "arena_center_x": 0.0,
        "arena_center_y": 0.0,
        "obstacles": [],
        "target_radius_m": 0.15,
        "plume_model": "puff",
        "plume_config": {},
        "environment_seed": 1_700_000_000,
    }
    events = [
        {"stamp": 0.5, "episode_id": 0, "active": True, "parameters": parameters},
        {"stamp": 2.0, "episode_id": 0, "active": False, "parameters": parameters},
    ]
    times = np.arange(0.0, 2.5, 0.01)
    agent = np.stack([times, 0.1 * times, np.zeros_like(times), 0.05 * times], axis=1)
    target = np.stack(
        [times, 2.0 + 0.2 * times, 0.3 * np.ones_like(times), np.zeros_like(times)], 1
    )
    arrays = {"agent": agent, "target": target, "events_json": np.array(json.dumps(events))}
    for eye in (0, 1):
        stamps = np.arange(0.52, 2.0, 1 / 30)
        frames = []
        for t in stamps:
            a, g = module.interpolate(agent, t), module.interpolate(target, t)
            frames.append(vision_transform(module.render_2d(env, a, g, parameters, eye)))
        arrays[f"vision{eye}_t"], arrays[f"vision{eye}"] = stamps, np.stack(frames)
    plume = make_plume("puff", {}, parameters["environment_seed"])
    odor = []
    for t in np.arange(0.52, 2.0, 1 / 50):
        a, g = module.interpolate(agent, t), module.interpolate(target, t)
        plume.advance(t - 0.5, np.asarray([g[:2]]))
        left, right = plume.concentration(odor_sensor_positions(a, env.contract.odor_baseline_m))
        odor.append((t, left, right, 1.0))
    arrays["odor"] = np.array(odor)
    return arrays


@pytest.fixture(scope="module")
def env():
    world = FlyTrackEnv(domain_randomization=False)
    world.reset(seed=0)
    return world


def test_identical_inputs_are_accepted(env):
    module = compare_module()
    result = module.compare(synthetic_export(module, env), env, env.contract)
    assert result["accepted"]
    for eye in result["vision"].values():
        assert eye["frames"] == 45
        assert eye["50_r"] == pytest.approx(1.0)
        assert eye["50_mad"] == pytest.approx(0.0, abs=1e-6)
        assert eye["median_gz_target_contrast"] > 0
        assert eye["median_gz_target_contrast"] == pytest.approx(eye["median_2d_target_contrast"])
    assert result["odor"]["samples"] == 74
    assert result["odor"]["r_left"] == pytest.approx(1.0)
    assert result["odor"]["median_abs_diff"] == pytest.approx(0.0, abs=1e-9)


def test_contrast_inverted_inputs_are_rejected(env):
    module = compare_module()
    result = module.compare(synthetic_export(module, env, lambda v: 1 - v), env, env.contract)
    assert not result["accepted"]
    for eye in result["vision"].values():
        assert eye["50_r"] == pytest.approx(-1.0)
        assert eye["median_gz_target_contrast"] < 0 < eye["median_2d_target_contrast"]


def test_windows_and_interpolation():
    module = compare_module()
    track = np.array([[0.0, 0.0, 0.0, np.pi - 0.1], [1.0, 1.0, 2.0, -np.pi + 0.1]])
    pose = module.interpolate(track, 0.5)
    assert pose[:2] == pytest.approx([0.5, 1.0])
    assert abs(np.angle(np.exp(1j * pose[2]))) == pytest.approx(np.pi)  # shortest way round
    assert module.interpolate(track, -1) is None and module.interpolate(track, 2) is None
    events = [
        {"stamp": 0.0, "episode_id": 0, "active": False, "parameters": {"episode_start_s": 0}},
        {"stamp": 1.0, "episode_id": 0, "active": True, "parameters": {"episode_start_s": 1.0}},
        {"stamp": 5.0, "episode_id": 0, "active": False, "parameters": {}},
        {"stamp": 6.0, "episode_id": 1, "active": True, "parameters": {"episode_start_s": 6.0}},
    ]
    windows = module.episode_windows(events)
    assert [(w[0], w[1], w[2]) for w in windows] == [(0, 1.0, 5.0), (1, 6.0, np.inf)]
